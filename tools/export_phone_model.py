"""Export artwork/phone/phone.bbmodel and its textures to the shared game assets."""

import json
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "artwork" / "phone"
ASSETS = ROOT / "common" / "src" / "main" / "resources" / "assets" / "sh_common_lib"
MATERIALS = {"phone.png": "body", "phone_screen.png": "screen"}


def face_normal(points):
    """Return an area-weighted normal for one triangle or quad."""
    ax, ay, az = (b - a for a, b in zip(points[0], points[1]))
    bx, by, bz = (c - a for a, c in zip(points[0], points[2]))
    return ay * bz - az * by, az * bx - ax * bz, ax * by - ay * bx


def mesh_normals(vertices, faces):
    totals = {key: [0.0, 0.0, 0.0] for key in vertices}
    for face in faces:
        keys = face["vertices"]
        normal = face_normal([vertices[key] for key in keys])
        for key in keys:
            for axis, component in enumerate(normal):
                totals[key][axis] += component

    return {
        key: tuple(component / math.hypot(*normal) for component in normal)
        for key, normal in totals.items()
    }


def export_obj(model):
    textures = model["textures"]
    positions = []
    normals = []
    uv_indices = {}
    geometry = []
    for mesh in model["elements"]:
        if mesh["type"] != "mesh" or any(mesh.get("rotation", ())):
            raise ValueError(f"Expected an unrotated mesh: {mesh['name']}")

        vertices = mesh["vertices"]
        faces = list(mesh["faces"].values())
        corner_normals = mesh_normals(vertices, faces)
        indices = {}
        for key, (x, y, z) in vertices.items():
            indices[key] = len(positions) + 1
            positions.append((x / 16 + 0.5, y / 16, z / 16 + 0.5))
            normals.append(corner_normals[key])

        geometry.append(f"o part_{len(positions)}")
        for material_index, texture in enumerate(textures):
            material = MATERIALS[texture["name"]]
            matching_faces = [face for face in faces if face["texture"] == material_index]
            if not matching_faces:
                continue
            geometry.append(f"usemtl {material}")
            for face in matching_faces:
                keys = face["vertices"]
                if not 3 <= len(keys) <= 4:
                    raise ValueError(f"Expected triangles or quads: {mesh['name']}")
                corners = []
                for key in keys:
                    u, v = face["uv"][key]
                    # Forge and NeoForge read OBJ V from the top with their default settings.
                    uv = u / texture["uv_width"], v / texture["uv_height"]
                    uv_index = uv_indices.setdefault(uv, len(uv_indices) + 1)
                    vertex_index = indices[key]
                    corners.append(f"{vertex_index}/{uv_index}/{vertex_index}")
                geometry.append("f " + " ".join(corners))

    lines = ["# Generated by tools/export_phone_model.py", "mtllib phone.mtl"]
    lines.extend(f"v {x:.8f} {y:.8f} {z:.8f}" for x, y, z in positions)
    lines.extend(f"vt {u:.8f} {v:.8f}" for u, v in uv_indices)
    lines.extend(f"vn {x:.8f} {y:.8f} {z:.8f}" for x, y, z in normals)
    lines.extend(geometry)
    return "\n".join(lines) + "\n"


def main():
    model = json.loads((SOURCE / "phone.bbmodel").read_text(encoding="utf-8"))
    if model["meta"]["model_format"] != "free":
        raise ValueError("Expected a Blockbench generic model")
    if {texture["name"] for texture in model["textures"]} != MATERIALS.keys():
        raise ValueError("Expected the body and screen textures")

    obj = export_obj(model)
    textures = {name: (SOURCE / name).read_bytes() for name in MATERIALS}
    item_models = ASSETS / "models" / "item"
    (item_models / "phone.obj").write_text(obj, encoding="utf-8", newline="\n")
    materials = ["# Generated by tools/export_phone_model.py"]
    materials.extend(f"newmtl {name}\nKd 1 1 1\nmap_Kd #{name}" for name in MATERIALS.values())
    (item_models / "phone.mtl").write_text("\n\n".join(materials) + "\n", encoding="utf-8", newline="\n")
    for name, texture in textures.items():
        (ASSETS / "textures" / "item" / name).write_bytes(texture)
    print(f"Exported {len(model['elements'])} meshes and {len(textures)} textures.")


if __name__ == "__main__":
    main()
