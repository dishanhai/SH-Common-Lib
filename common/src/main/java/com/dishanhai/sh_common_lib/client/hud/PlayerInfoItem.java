package com.dishanhai.sh_common_lib.client.hud;

import java.util.Locale;

public enum PlayerInfoItem {
    PLAYER, FPS, PING, LOCAL_TIME, WORLD_TIME, WEATHER, DIMENSION, CHUNKS, ENTITIES, BIOME, POSITION, CHUNK, LIGHT,
    TPS, MSPT, MEMORY, CPU, GPU, DISK, JAVA_VERSION, MINECRAFT_VERSION, FORGE_VERSION, NEOFORGE_VERSION,
    SHADER_PACK, MOD_STATUS, MOON_PHASE, HEALTH, FOOD, ARMOR, EXPERIENCE, AIR, EFFECTS,
    SYSTEM_VERSION, CONNECTION_TRAFFIC, NETWORK_TRAFFIC, AE2_STATUS, AE2_CHANNELS, AE2_POWER,
    FTB_QUESTS, FTB_TEAM, FTB_CHUNKS, FTB_CHUNK_INFO, ULK_SUMMARY, ULK_SOURCES, NEOECO_NETWORK,
    NEOECO_CRAFTING, NEOECO_COMPUTATION, NEOECO_STORAGE, NEOECO_WORKSTATION;

    public String id() {
        return name().toLowerCase(Locale.ROOT);
    }

    boolean defaultVisible() {
        return switch (this) {
            case TPS, MSPT, MEMORY, CPU, GPU, DISK, JAVA_VERSION, MINECRAFT_VERSION, FORGE_VERSION,
                    NEOFORGE_VERSION, SHADER_PACK, MOD_STATUS, MOON_PHASE, HEALTH, FOOD, ARMOR, EXPERIENCE,
                    AIR, EFFECTS, SYSTEM_VERSION, CONNECTION_TRAFFIC, NETWORK_TRAFFIC, AE2_STATUS, AE2_CHANNELS,
                    AE2_POWER, FTB_QUESTS, FTB_TEAM, FTB_CHUNKS, FTB_CHUNK_INFO, ULK_SUMMARY, ULK_SOURCES, NEOECO_NETWORK,
                    NEOECO_CRAFTING, NEOECO_COMPUTATION, NEOECO_STORAGE, NEOECO_WORKSTATION -> false;
            default -> true;
        };
    }
}
